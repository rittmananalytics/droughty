"""Where droughty's dbt schema files live, and how to tell them apart from other YAML files.

Uses only the standard library, so the droughty GitHub check can import it
without installing droughty's other packages.
"""

import glob
import os


# Only written to per-layer files, so single-file output is unchanged. Droughty
# deletes or reports a layer file only when it starts with this line.
GENERATED_HEADER = "# Generated by droughty. Changes made here will be overwritten.\n"


def schema_file_path(git_path, dbt_path, dbt_tests_filename):

    """Return the path of the schema file: <git root>/<dbt_path or models>/<filename or droughty_schema>.yml"""

    if dbt_path == None:

        path = os.path.join(git_path, "models")

    else:

        path = os.path.join(git_path, dbt_path)

    if dbt_tests_filename != None:

        filename = dbt_tests_filename

    else:

        filename = 'droughty_schema'

    return os.path.join(path, filename + '.yml')


def layer_file_path(git_path, dbt_path, dbt_tests_filename, layer):

    """<dbt_path>/<filename>_<layer>.yml, next to where the single file is written."""

    single = schema_file_path(git_path, dbt_path, dbt_tests_filename)

    return single[:-len('.yml')] + '_' + layer + '.yml'


def _generated_by_droughty(path):

    try:
        with open(path) as f:
            return f.readline() == GENERATED_HEADER
    except OSError:
        return False


def schema_files_on_disk(git_path, dbt_path, dbt_tests_filename):

    """Return the droughty schema files that exist on disk.

    That is the single file, plus any <filename>_*.yml that starts with droughty's
    header line, so files for layers removed from dbt_layers are found too.
    """

    single = schema_file_path(git_path, dbt_path, dbt_tests_filename)

    layer_files = glob.glob(glob.escape(single[:-len('.yml')]) + '_*.yml')

    found = []

    for path in [single] + sorted(layer_files):

        if not os.path.exists(path):
            continue

        # the single file has always been droughty's; layer files must carry the header
        if path == single or _generated_by_droughty(path):
            found.append(path)

    return found


def stale_schema_files(files, git_path, dbt_path, dbt_tests_filename):

    """Return droughty schema files on disk that the current run does not write.

    These are left over from switching between single and per_layer output, or
    from a layer that no longer has models. dbt fails if a model is described
    in two files, so they need removing.
    """

    return [path for path in schema_files_on_disk(git_path, dbt_path, dbt_tests_filename) if path not in files]


def is_droughty_schema_file(path, git_path, dbt_path, dbt_tests_filename):

    """True if path is the single schema file or a <filename>_<layer>.yml file next to it."""

    single = os.path.realpath(schema_file_path(git_path, dbt_path, dbt_tests_filename))
    path = os.path.realpath(path)

    if path == single:
        return True

    prefix = single[:-len('.yml')] + '_'

    return path.startswith(prefix) and path.endswith('.yml') and os.sep not in path[len(prefix):]


def patch_file(model, dbt_dir):

    """Return the full path of the YAML file that describes a model, or None.

    The manifest stores it as patch_path, for example my_project://models/staging/_staging.yml,
    relative to the dbt project folder.
    """

    patch_path = model.get('patch_path')

    if not patch_path:
        return None

    return os.path.join(dbt_dir, patch_path.split('://', 1)[-1])


def described_elsewhere(models, git_path, dbt_dir, dbt_path, dbt_tests_filename):

    """Return {model name: YAML file} for models described in a YAML file that is not droughty's.

    dbt fails if a model is described in two files, so droughty leaves these out.
    models is the output of select_models.
    """

    found = {}

    for name, model in models.items():

        path = patch_file(model, dbt_dir)

        if path and not is_droughty_schema_file(path, git_path, dbt_path, dbt_tests_filename):
            found[name] = path

    return found
